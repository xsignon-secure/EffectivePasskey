import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from effective_passkey import html_report, remediation, report  # noqa: E402
from effective_passkey.diff import diff  # noqa: E402
from effective_passkey.fleet import run_fleet  # noqa: E402
from effective_passkey.model import InputError, load_tenant  # noqa: E402
from effective_passkey.rules import Auditor  # noqa: E402

DEMOS = os.path.join(ROOT, "examples", "demo-tenants")
AS_OF = date(2026, 10, 22)


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def audit(name_or_dir):
    d = name_or_dir if os.path.isdir(name_or_dir) else os.path.join(DEMOS, name_or_dir)
    a = Auditor(load_tenant(d), AS_OF)
    a.run()
    return a


class RemediationTests(unittest.TestCase):
    def test_contoso_plan_removes_admin_synced_exposure(self):
        before = audit("contoso")
        plan = remediation.build_plan(before)
        o = plan.outcome()
        self.assertEqual(o["privilegedSyncedBefore"], 3)
        self.assertEqual(o["privilegedSyncedAfter"], 0)
        self.assertTrue(any("R1" in c.fixes for c in plan.changes))
        # source tenant is untouched
        self.assertEqual(before.tenant.fido2.include_targets[0].id, "all_users")

    def test_proposed_export_reproduces_simulation(self):
        for name in ("contoso", "fabrikam", "northwind"):
            plan = remediation.build_plan(audit(name))
            with tempfile.TemporaryDirectory() as out:
                remediation.write_plan(plan, out)
                again = audit(os.path.join(out, "proposed-export"))
                self.assertEqual(sorted(f.key for f in again.findings), sorted(f.key for f in plan.after.findings), name)
                for f in ("remediation.md", "remediation.json", "remediation.html"):
                    self.assertTrue(os.path.isfile(os.path.join(out, f)))

    def test_breakglass_stays_excluded(self):
        plan = remediation.build_plan(audit("contoso"))
        self.assertEqual(plan.after.policies["u-bg1"].status, "excluded")
        self.assertFalse(any("breakglass" in c.title for c in plan.changes))

    def test_northwind_gives_sms_users_a_path_and_admin_profile(self):
        plan = remediation.build_plan(audit("northwind"))
        titles = " ".join(c.title for c in plan.changes)
        self.assertIn("Convert legacy", titles)
        self.assertIn("Create profile 'Admins - device-bound, attested'", titles)
        self.assertEqual(plan.after.policies["u-ravi"].status, "allowed")
        self.assertEqual(plan.after.policies["u-oscar"].rank, 2)

    def test_fabrikam_fixes_aaguid_trap_and_attested_synced(self):
        plan = remediation.build_plan(audit("fabrikam"))
        after_rules = {f.rule for f in plan.after.findings}
        self.assertNotIn("R5", after_rules)
        self.assertNotIn("R1", after_rules)
        self.assertNotIn("synced", plan.tenant.fido2.profiles["pp-admin"].passkey_types)

    def test_plan_is_deterministic(self):
        a = json.dumps(remediation.build_plan(audit("northwind")).to_dict(), sort_keys=True)
        b = json.dumps(remediation.build_plan(audit("northwind")).to_dict(), sort_keys=True)
        self.assertEqual(a, b)


class StableKeyTests(unittest.TestCase):
    def test_r3_severity_change_is_not_new_finding(self):
        before = report.build_result(audit("northwind"))
        after = report.build_result(remediation.build_plan(audit("northwind")).after)
        d = diff(before, after)
        changed = {c["subject"]: (c["before"], c["after"]) for c in d["severityChanges"]}
        self.assertEqual(changed["ravi@northwind.example"], ("critical", "high"))
        self.assertFalse(any(f["rule"] == "R3" for f in d["newFindings"]))


class BrandTests(unittest.TestCase):
    def test_bad_colour_rejected(self):
        with self.assertRaises(ValueError):
            html_report.Brand.build(color="red; background:url(x)")

    def test_logo_embedded_and_names_escaped(self):
        with tempfile.TemporaryDirectory() as d:
            logo = os.path.join(d, "l.svg")
            with open(logo, "w") as fh:
                fh.write("<svg xmlns='http://www.w3.org/2000/svg'/>")
            b = html_report.Brand.build(name="<b>Acme</b>", color="#0a7d5a", logo=logo, prepared_for="Contoso & Co")
        page = html_report.render(report.build_result(audit("contoso")), b)
        self.assertIn("data:image/svg+xml;base64,", page)
        self.assertIn("&lt;b&gt;Acme&lt;/b&gt;", page)
        self.assertIn("Contoso &amp; Co", page)
        self.assertIn("--accent:#0a7d5a", page)
        self.assertIn("Generated by EffectivePasskey", page)

    def test_unsupported_logo_rejected(self):
        with self.assertRaises(ValueError):
            html_report.Brand.build(logo="logo.exe")


class FleetTests(unittest.TestCase):
    def test_fleet_dashboard_and_drift(self):
        with tempfile.TemporaryDirectory() as out:
            first = os.path.join(out, "m1")
            f1 = run_fleet(DEMOS, first, AS_OF, with_remediation=True)
            self.assertEqual([r["key"] for r in f1["tenants"]], ["northwind", "contoso", "fabrikam"])
            self.assertEqual(f1["totals"]["privilegedSyncedAllowed"], 5)
            page = read(os.path.join(first, "index.html"))
            self.assertIn('href="contoso/report.html"', page)
            self.assertTrue(os.path.isfile(os.path.join(first, "contoso", "remediation", "remediation.html")))
            f2 = run_fleet(DEMOS, os.path.join(out, "m2"), date(2026, 11, 22), previous=first)
            self.assertEqual(f2["tenants"][0]["drift"]["newFindings"], 0)

    def test_broken_tenant_is_reported_not_fatal(self):
        with tempfile.TemporaryDirectory() as d:
            shutil.copytree(os.path.join(DEMOS, "contoso"), os.path.join(d, "good"))
            os.makedirs(os.path.join(d, "bad"))
            for f in ("policy", "groups", "users", "roles"):
                with open(os.path.join(d, "bad", f + ".json"), "w") as fh:
                    fh.write("{not json")
            fleet = run_fleet(d, os.path.join(d, "out"), AS_OF)
            self.assertEqual(len(fleet["tenants"]), 1)
            self.assertEqual(fleet["errors"][0]["tenant"], "bad")

    def test_empty_folder_is_input_error(self):
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaises(InputError):
                run_fleet(d, os.path.join(d, "out"), AS_OF)


class CliAndSiteTests(unittest.TestCase):
    def run_cli(self, *args):
        return subprocess.run([sys.executable, "-m", "effective_passkey", *args], cwd=ROOT, capture_output=True, text=True)

    def test_fleet_fail_on_grade(self):
        with tempfile.TemporaryDirectory() as out:
            p = self.run_cli("fleet", DEMOS, "-o", out, "--as-of", "2026-10-22", "--fail-on-grade", "D", "-q")
            self.assertEqual(p.returncode, 1, p.stderr)

    def test_remediate_cli(self):
        with tempfile.TemporaryDirectory() as out:
            p = self.run_cli("remediate", os.path.join(DEMOS, "contoso"), "-o", out, "--as-of", "2026-10-22")
            self.assertEqual(p.returncode, 0, p.stderr)
            self.assertIn("3 → 0", p.stdout)

    def test_site_builds(self):
        with tempfile.TemporaryDirectory() as out:
            p = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "build_site.py"), "--out", out,
                                "--as-of", "2026-10-22"], capture_output=True, text=True)
            self.assertEqual(p.returncode, 0, p.stderr)
            index = read(os.path.join(out, "index.html"))
            self.assertIn(">102<", index)
            self.assertNotIn("__", index.replace("__init__", ""))
            for path in ("demo/contoso/report.html", "demo/fleet/index.html", "demo/northwind/remediation/remediation.html"):
                self.assertTrue(os.path.isfile(os.path.join(out, path)), path)


if __name__ == "__main__":
    unittest.main()
